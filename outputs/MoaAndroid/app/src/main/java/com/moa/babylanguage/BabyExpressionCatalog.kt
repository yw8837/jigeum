package com.moa.babylanguage

/** Authored first-person sound expressions. Requests and playful metaphors are
 * character wording, never inferred causes, transcripts, or measured emotions.
 * Every opening pairs with every reply in its own evidence family. */
internal object BabyExpressionCatalog {
    class Family(val openings: List<String>, val replies: List<String>) {
        // A view keeps selection O(1); do not allocate hundreds of unused strings
        // on every analysis. The diagonal changes both halves for nearby keys and
        // still visits every pair exactly once. It contains no session/random state.
        val phrases: List<String> = object : AbstractList<String>() {
            override val size = openings.size * replies.size
            override fun get(index: Int): String {
                require(index in indices)
                val first = index % openings.size
                val second = (first + index / openings.size) % replies.size
                return "${openings[first]} ${replies[second]}"
            }
        }
    }

