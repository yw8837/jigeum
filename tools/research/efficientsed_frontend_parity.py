ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
MODEL_SHA = '0a1bf37323cb9069d26a63b0ca4486c9c027b29e3bff087e0acd7270022716fc'
CASES = ('silence', 'tone', 'noise', 'boundary_impulse', 'dc', 'quiet', 'multitone')
MEL_ATOL = 2e-4
OUTPUT_ATOL = 1e-4
OUTPUT_RTOL = 1e-3


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def official_frontend(source):
    """Read the pinned wrapper's literal constructor args; execute official class."""
    pin = json.loads((HERE / 'efficientsed-models.json').read_text(encoding='utf-8'))
    for relative, expected in pin['source_files'].items():
        if digest(source / relative) != expected:
            raise ValueError('Source hash mismatch: ' + relative)
    tree = ast.parse((source / 'models/efficient_cnns/fmn/fmn_wrapper.py').read_text(encoding='utf-8'))
    calls = [n for n in ast.walk(tree) if isinstance(n, ast.Call)
             and isinstance(n.func, ast.Name) and n.func.id == 'AugmentMelSTFT']
    if len(calls) != 1 or calls[0].args:
        raise ValueError('Unexpected official frontend constructor')
    kwargs = {k.arg: ast.literal_eval(k.value) for k in calls[0].keywords}
    spec = importlib.util.spec_from_file_location('pinned_sed_preprocess', source / 'models/transformers/frame_passt/preprocess.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    frontend = module.AugmentMelSTFT(**kwargs).float().eval()
    if (frontend.n_mels, frontend.sr, frontend.n_fft, frontend.win_length,
            frontend.hopsize, frontend.fmin, frontend.fmax, frontend.padding,
            frontend.preamp, frontend.fast_norm) != (128, 16000, [512], [400], 160, 0., 7000, 'center', True, True):
        raise ValueError('Official configuration differs from Kotlin contract')
    return frontend, kwargs, pin


def table_source(frontend):
    import torch
    import torchaudio
    banks, _ = torchaudio.compliance.kaldi.get_mel_banks(128, 512, 16000, 0., 7000,
                                                       100., -500., 1.)
    # Kotlin requires a decimal point in floating literals (including 0/1).
    def kotlin_floats(values):
        return ', '.join((s if '.' in s or 'e' in s else s + '.0') + 'f'
                         for s in [format(float(x), '.9g') for x in values])
    hann = frontend.window_400.cpu().numpy()
    basis = torch.nn.functional.pad(banks, (0, 1)).cpu().numpy()
    rows = ['package research.efficientsed', '',
            '// Generated by efficientsed_frontend_parity.table_source from pinned official eval tensors.',
            '// source e3449bfd1f4922b81d82410ed842653f462bfca8; torch/torchaudio 2.11.0+cpu.',
            '// 400-point nonperiodic Hann; Kaldi 128 mel, 16kHz, FFT512, 0..7000Hz; Nyquist weight=0.',
            'internal object EfficientSedTables {',
            '    val hann = floatArrayOf(']
    rows += ['        ' + kotlin_floats(hann[i:i+8]) + ',' for i in range(0, 400, 8)]
    rows += ['    )', '    val bins = arrayOf(']
    for bank in basis:
        rows.append('        intArrayOf(' + ', '.join(str(i) for i in bank.nonzero()[0]) + '),')
    rows += ['    )', '    val weights = arrayOf(']
    for bank in basis:
        rows.append('        floatArrayOf(' + kotlin_floats(bank[bank != 0]) + '),')
    rows += ['    )', '}', '']
    return '\n'.join(rows)


def compiler_paths(cache):
    """Use already installed compiler dependencies only; never invoke Gradle."""
    names = [('org.jetbrains.kotlin', 'kotlin-compiler-embeddable', '2.2.10'),
             ('org.jetbrains.kotlin', 'kotlin-stdlib', '2.2.10'),
             ('org.jetbrains.kotlin', 'kotlin-script-runtime', '2.2.10'),
             ('org.jetbrains.kotlin', 'kotlin-daemon-embeddable', '2.2.10'),
             ('org.jetbrains.kotlin', 'kotlin-reflect', '2.2.0'),
             ('org.jetbrains.kotlinx', 'kotlinx-coroutines-core-jvm', '1.8.0'),
             ('org.jetbrains', 'annotations', '13.0')]
    jars = []
    for group, name, version in names:
        matches = list((cache / group / name / version).glob('*/*.jar'))
        if len(matches) != 1:
            raise FileNotFoundError('Need one cached compiler jar: ' + name + '/' + version)
        jars.append(matches[0])
    return jars, jars[1]


def load_model(source, assets, pin):
    import torch
    from models.efficient_cnns.fmn.fmn_wrapper import FrameMNWrapper
    from models.sequence_models.helper import init_weights
    from models.sequence_models.roformer.transformer_block import TransformerBlock
    file = source / 'models/prediction_wrapper.py'
    tree = ast.parse(file.read_text(encoding='utf-8'))
    classes = [x for x in tree.body if isinstance(x, ast.ClassDef) and x.name == 'PredictionsWrapper']
    if len(classes) != 1:
        raise ValueError('Unexpected official prediction wrapper')
    ns = dict(torch=torch, nn=torch.nn, warnings=warnings,
              init_weights=init_weights, TransformerBlock=TransformerBlock)
    exec(compile(ast.Module(body=classes, type_ignores=[]), str(file), 'exec'), ns)
    base = FrameMNWrapper(1.0)
    dim = base.state_dict()['fmn.features.16.1.bias'].shape[0]
    model = ns['PredictionsWrapper'](base, checkpoint=None, seq_model_type='tf',
                                   seq_model_dim=256, embed_dim=dim).float().eval()
    asset = next(x for x in pin['weights'] if x['name'] == 'fmn10+tf-256_advanced-kd-weak-strong.pt')
    weights = assets / asset['name']
    if weights.stat().st_size != asset['size'] or digest(weights) != asset['sha256']:
        raise ValueError('Weight pin mismatch')
    raw = torch.load(weights, map_location='cpu', weights_only=True)
    state = {('model.' + k[4:] if k.startswith('net.') else k): v for k, v in raw.items()}
    state = {('model.fmn.' + k[len('model.model.'):] if k.startswith('model.model.') else k): v for k, v in state.items()}
    state = {(k[len('model.'):] if not k.startswith('model.fmn.') else k): v for k, v in state.items()}
    model.load_state_dict(state, strict=True)
    return model


def completed(result):
    def finite_nonnegative(value):
        return type(value) in (int, float) and math.isfinite(value) and value >= 0
    rows = result.get('cases', [])
    if len(rows) != 7 or {r.get('case') for r in rows} != set(CASES):
        return False
    for row in rows:
        if row.get('mel_shape') != [1, 1, 128, 1000] or row.get('mel_finite') is not True or row.get('mel_passed') is not True:
            return False
        if (not finite_nonnegative(row.get('mel_max_absolute'))
                or row['mel_max_absolute'] > MEL_ATOL
                or not finite_nonnegative(row.get('mel_mean_absolute'))):
            return False
        outputs = row.get('outputs', [])
        expected = {(kind, index) for kind in ('frontend_delta_ort', 'end_to_end_torch') for index in (0, 1)}
        if len(outputs) != 4 or {(o.get('comparison'), o.get('output')) for o in outputs} != expected:
            return False
        if not all(o.get('finite') is True and o.get('passed') is True
                   and o.get('shape') == ([1, 447, 250] if o['output'] == 0 else [1, 447])
                   and finite_nonnegative(o.get('max_absolute'))
                   and finite_nonnegative(o.get('mean_absolute'))
                   and finite_nonnegative(o.get('max_scaled_error'))
                   and o['max_scaled_error'] <= 1. for o in outputs):
            return False
    return result.get('contracts_passed') is True and result.get('tables_exact') is True


def worker(args):
    def denied(*a, **kw):
        raise RuntimeError('Network prohibited during synthetic-only parity')
    socket.socket.connect = denied
    socket.socket.connect_ex = denied
    socket.create_connection = denied
    os.environ['HF_HUB_OFFLINE'] = '1'
    import numpy as np
    import torch
    import onnxruntime as ort
    torch.set_num_threads(4)
    torch.manual_seed(17)
    source = args.assets / 'source'
    sys.path.insert(0, str(source))
    frontend, config, pin = official_frontend(source)
    if torch.__version__ != '2.11.0+cpu':
        raise ValueError('Torch runtime differs from constants pin')
    candidate_tables = table_source(frontend)
    (args.output / 'oracle-tables.kt').write_text(candidate_tables, encoding='utf-8')
    if (HERE / 'efficientsed_tables.kt').read_text(encoding='utf-8') != candidate_tables:
        raise ValueError('Committed Kotlin constants differ from official tensors')
    if digest(args.onnx) != MODEL_SHA:
        raise ValueError('ONNX pin mismatch')
    jars, stdlib = compiler_paths(args.compiler_cache)
    classpath = os.pathsep.join(map(str, jars))
    target = args.output / 'kotlin-classes'
    target.mkdir()
    compiler = [args.java, '-Xmx512m', '-cp', classpath, 'org.jetbrains.kotlin.cli.jvm.K2JVMCompiler',
                '-no-stdlib', '-no-reflect', '-classpath', str(stdlib), '-jvm-target', '11', '-d', str(target)]
    compiler += [str(HERE / name) for name in ('efficientsed_frontend.kt', 'efficientsed_tables.kt', 'efficientsed_frontend_probe.kt')]
    subprocess.run(compiler, timeout=60, check=True)
    probe = [args.java, '-Xmx128m', '-cp', os.pathsep.join((str(target), str(stdlib))),
             'research.efficientsed.EfficientSedFrontendProbe']
    subprocess.run(probe + ['--self-test'], timeout=30, check=True)
    model = load_model(source, args.assets, pin)
    options = ort.SessionOptions()
    options.intra_op_num_threads = 4
    session = ort.InferenceSession(str(args.onnx), options, providers=['CPUExecutionProvider'])
    t = np.arange(160000, dtype=np.float64) / 16000.
    impulses = np.zeros(160000, np.float32)
    impulses[[0, 1, 199, 200, 159798, 159998, 159999]] = [.03, -.02, .05, -.04, .07, -.06, .08]
    samples = dict(silence=np.zeros(160000, np.float32),
                   tone=(.03 * np.sin(2 * np.pi * 440 * t)).astype(np.float32),
                   noise=np.random.default_rng(17).normal(0, .005, 160000).astype(np.float32),
                   boundary_impulse=impulses, dc=np.full(160000, .01, np.float32),
                   quiet=(1e-5 * np.sin(2 * np.pi * 997 * t)).astype(np.float32),
                   multitone=(.01 * np.sin(2 * np.pi * 123 * t) + .02 * np.sin(2 * np.pi * 997 * t)
                              + .005 * np.sin(2 * np.pi * 6800 * t)).astype(np.float32))
    result = dict(status='running', passed=False, android_validated=False, synthetic_only=True,
                  source_revision=pin['revision'], onnx_sha256=MODEL_SHA,
                  kotlin_sources={name: digest(HERE / name) for name in ('efficientsed_frontend.kt', 'efficientsed_tables.kt', 'efficientsed_frontend_probe.kt')},
                  versions=dict(torch=torch.__version__, ort=ort.__version__, numpy=np.__version__),
                  official_constructor=config, tables_exact=True, contracts_passed=True,
                  tolerance=dict(mel_absolute=MEL_ATOL, output_absolute=OUTPUT_ATOL, output_relative=OUTPUT_RTOL), cases=[])
    def save():
        (args.output / 'result.json').write_text(json.dumps(result, indent=2), encoding='utf-8')
    save()
    for name, pcm in samples.items():
        pcm_file = args.output / (name + '-pcm.f32')
        kotlin_file = args.output / (name + '-kotlin-mel.f32')
        pcm.astype('<f4').tofile(pcm_file)
        run = subprocess.run(probe + [str(pcm_file), str(kotlin_file)], timeout=30, check=True, capture_output=True, text=True)
        actual = np.fromfile(kotlin_file, dtype='<f4').reshape(1, 1, 128, 1000)
        with torch.no_grad():
            reference = frontend(torch.from_numpy(pcm).unsqueeze(0)).numpy()
            expected_outputs = tuple(x.numpy() for x in model(torch.from_numpy(reference)))
        reference.astype('<f4').tofile(args.output / (name + '-official-mel.f32'))
        error = np.abs(actual - reference)
        row = dict(case=name, pcm_sha256=digest(pcm_file), mel_shape=list(actual.shape),
                   mel_finite=bool(np.isfinite(actual).all() and np.isfinite(reference).all()),
                   mel_max_absolute=float(error.max()), mel_mean_absolute=float(error.mean()),
                   mel_worst_index=list(map(int, np.unravel_index(error.argmax(), error.shape))),
                   mel_passed=bool(np.isfinite(error).all() and error.max() <= MEL_ATOL),
                   host_jvm=json.loads(run.stdout), outputs=[])
        actual_outputs = session.run(None, {session.get_inputs()[0].name: actual})
        oracle_outputs = session.run(None, {session.get_inputs()[0].name: reference})
        for tag, outputs in [('kotlin-ort', actual_outputs), ('official-ort', oracle_outputs), ('official-torch', expected_outputs)]:
            for index, values in enumerate(outputs):
                values.astype('<f4').tofile(args.output / f'{name}-{tag}-{index}.f32')
        for comparison, outputs in [('frontend_delta_ort', oracle_outputs), ('end_to_end_torch', expected_outputs)]:
            for index, (a, b) in enumerate(zip(actual_outputs, outputs)):
                if a.shape != b.shape:
                    raise ValueError('Output shape mismatch')
                error = np.abs(a - b)
                row['outputs'].append(dict(comparison=comparison, output=index, shape=list(a.shape),
                    finite=bool(np.isfinite(a).all() and np.isfinite(b).all()),
                    max_absolute=float(error.max()), mean_absolute=float(error.mean()),
                    max_scaled_error=float(np.max(error / (OUTPUT_ATOL + OUTPUT_RTOL * np.abs(b)))),
                    passed=bool(np.allclose(a, b, rtol=OUTPUT_RTOL, atol=OUTPUT_ATOL))))
        result['cases'].append(row)
        save()
        print(json.dumps(row), flush=True)
    result['passed'] = completed(result)
    result['status'] = 'completed' if result['passed'] else 'failed'
    save()
    if not result['passed']:
        raise SystemExit(2)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--assets', type=Path, required=True)
    parser.add_argument('--onnx', type=Path, required=True)
    parser.add_argument('--java', default=shutil.which('java'))
    parser.add_argument('--compiler-cache', type=Path, default=Path.home() / '.gradle/caches/modules-2/files-2.1')
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--worker', action='store_true')
    args = parser.parse_args()
    args.assets = args.assets.resolve(strict=True)
    args.onnx = args.onnx.resolve(strict=True)
    args.output = args.output.resolve()
    validate_output_path(args.output)
    if args.worker:
        try:
            worker(args)
        except Exception as exc:
            path = args.output / 'result.json'
            result = json.loads(path.read_text(encoding='utf-8')) if path.exists() else {}
            result.update(status='failed', passed=False, exception_type=type(exc).__name__, error=str(exc)[:3000])
            path.write_text(json.dumps(result, indent=2), encoding='utf-8')
            raise
        return
    args.output.mkdir(parents=True, exist_ok=False)
    from bounded_process import run_bounded
    argv = [sys.executable, str(Path(__file__).resolve()), '--worker', '--assets', str(args.assets),
            '--onnx', str(args.onnx), '--java', args.java, '--compiler-cache', str(args.compiler_cache), '--output', str(args.output)]
    process = run_bounded(argv, cwd=ROOT, log_path=args.output / 'parity.log', timeout_seconds=180,
                          memory_limit_bytes=4 * 1024**3, env=dict(os.environ))
    (args.output / 'process.json').write_text(json.dumps(asdict(process), indent=2), encoding='utf-8')
    if process.exit_code or process.termination or not process.cleanup_complete:
        raise SystemExit('Bounded parity failed; inspect parity.log/process.json/result.json')
    result = json.loads((args.output / 'result.json').read_text(encoding='utf-8'))
    if result.get('passed') is not True or result.get('status') != 'completed' or not completed(result):
        raise SystemExit('Parity result failed independent gate validation')
    print(json.dumps(dict(passed=True, cases=len(result['cases']), android_validated=False,
                         mel_max_absolute=max(r['mel_max_absolute'] for r in result['cases']),
                         output_max_absolute=max(o['max_absolute'] for r in result['cases'] for o in r['outputs']),
                         elapsed_seconds=process.elapsed_seconds)))


if __name__ == '__main__':
    main()
